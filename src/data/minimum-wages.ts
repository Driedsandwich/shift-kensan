export const minimumWages = rows.map(
  ([prefecture, amount, previous, effective]) => ({
    prefecture,
    amount,
    previous,
    effective: `2026-${effective}`,
  }),
);
export function minimumAt(prefecture: string, date: string) {
  if (date < SUPPORTED_FROM || date > SUPPORTED_TO)
    throw new Error("最低賃金の確認済み期間は 2026-04-01〜2026-12-31 です。");
  const row = minimumWages.find((r) => r.prefecture === prefecture);
  if (!row) throw new Error("働く場所の都道府県を選んでください。");
  return { ...row, applied: date >= row.effective ? row.amount : row.previous };
}
